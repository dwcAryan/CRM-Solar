"""
Orchestration service for Solar CRM AI Assist.
Handles context compilation, hash-based caching, per-user rate limiting,
provider execution, and seamless fallback to the rules engine.
"""

from __future__ import annotations

import logging
from typing import TYPE_CHECKING, Any

from django.conf import settings
from django.utils import timezone

from leads.models import AISuggestion

from .context_builder import build_lead_summary_context
from .providers import AnthropicProvider, RulesProvider

if TYPE_CHECKING:
    from accounts.models import User
    from leads.models import Lead

logger = logging.getLogger(__name__)


def get_or_generate_ai_suggestion(
    lead: Lead,
    user: User | None = None,
    force_refresh: bool = False,
) -> tuple[AISuggestion, bool]:
    """
    Retrieves a cached AI suggestion or generates a new one.

    Returns:
        tuple[AISuggestion, bool]: (suggestion_instance, is_newly_generated)
    """
    context, input_hash = build_lead_summary_context(lead)

    # 1. Cache hit check (unless forced refresh)
    if not force_refresh:
        existing = AISuggestion.objects.filter(lead=lead, input_hash=input_hash).order_by('-generated_at').first()
        if existing:
            return existing, False

    # 2. Rate limit check per user per day
    today_start = timezone.now().replace(hour=0, minute=0, second=0, microsecond=0)
    max_daily_calls = getattr(settings, 'AI_MAX_CALLS_PER_USER_PER_DAY', 50)
    rate_limited = False

    if user and user.is_authenticated:
        user_calls_today = AISuggestion.objects.filter(
            generated_by=user,
            generated_at__gte=today_start,
            is_fallback=False,
            provider=AISuggestion.Provider.ANTHROPIC,
        ).count()
        if user_calls_today >= max_daily_calls:
            rate_limited = True
            logger.warning(f"User {user.id} exceeded daily AI call quota ({user_calls_today}/{max_daily_calls}).")

    # 3. Provider determination
    target_provider = getattr(settings, 'AI_PROVIDER', 'rules').lower()
    anthropic_key = getattr(settings, 'ANTHROPIC_API_KEY', '').strip()
    ai_model = getattr(settings, 'AI_MODEL', 'claude-sonnet-5-5')

    suggestion_data: dict[str, Any] = {}
    tokens_used = 0
    provider_name = AISuggestion.Provider.RULES
    model_name = "rules-engine"
    is_fallback = False
    error_message = ""

    # Attempt Anthropic if configured, key is present, and user is not rate-limited
    if target_provider == 'anthropic' and anthropic_key and not rate_limited:
        try:
            anthropic_provider = AnthropicProvider(api_key=anthropic_key, model=ai_model)
            suggestion_data, tokens_used = anthropic_provider.generate(context)
            provider_name = AISuggestion.Provider.ANTHROPIC
            model_name = ai_model
            suggestion_data["provider_source"] = "Anthropic Claude"
            suggestion_data["provider_note"] = f"Generated by {ai_model}"
        except Exception as e:
            # Anonymized failure logging (never log personal data)
            error_message = str(e)[:300]
            logger.warning(f"AnthropicProvider failed for Lead #{lead.id}: {error_message}. Falling back to RulesProvider.")
            is_fallback = True

    # Fallback or default to RulesProvider
    if not suggestion_data:
        rules_provider = RulesProvider()
        suggestion_data, _ = rules_provider.generate(context)
        provider_name = AISuggestion.Provider.RULES
        model_name = "rules-engine"

        if rate_limited:
            suggestion_data["provider_source"] = "Rules Engine (Quota Limit)"
            suggestion_data["provider_note"] = f"Daily AI quota reached ({max_daily_calls}/day). Recommendation generated via Rules Engine."
            is_fallback = True
        elif is_fallback:
            suggestion_data["provider_source"] = "Rules Engine (Fallback)"
            suggestion_data["provider_note"] = "AI service temporarily unavailable. Recommendation generated via Rules Engine."
        else:
            suggestion_data["provider_source"] = "Rules Engine"
            suggestion_data["provider_note"] = "Generated by Solar CRM Rule-Based Expert Engine."

    # 4. Save to AISuggestion table
    suggestion = AISuggestion.objects.create(
        lead=lead,
        generated_by=user if user and user.is_authenticated else None,
        provider=provider_name,
        model=model_name,
        input_hash=input_hash,
        output_json=suggestion_data,
        tokens_used=tokens_used,
        is_fallback=is_fallback,
        error_message=error_message,
    )

    return suggestion, True
